-- Run the whole script in a Snowsight SQL worksheet as an administrator.
-- Prerequisites: existing SEMESTEROS_API service user and its registered public key.
-- Replace COMPUTE_WH below if the backend uses a different existing warehouse.
USE ROLE ACCOUNTADMIN;

-- Ensure each parent exists before creating or granting access to its children.
CREATE DATABASE IF NOT EXISTS SEMESTEROS;
CREATE SCHEMA IF NOT EXISTS SEMESTEROS.APP;
CREATE STAGE IF NOT EXISTS SEMESTEROS.APP.SYLLABI;

CREATE TABLE IF NOT EXISTS SEMESTEROS.APP.SYLLABUS_UPLOADS (
    ID VARCHAR PRIMARY KEY,
    ORIGINAL_FILENAME VARCHAR NOT NULL,
    STAGED_FILENAME VARCHAR NOT NULL,
    SIZE_BYTES NUMBER NOT NULL,
    STATUS VARCHAR NOT NULL,
    CREATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONFIRMED_AT TIMESTAMP_LTZ,
    CONFIRMED VARIANT
);

-- Upgrade the earlier upload-metadata table if it already exists.
ALTER TABLE SEMESTEROS.APP.SYLLABUS_UPLOADS ADD COLUMN IF NOT EXISTS CONFIRMED VARIANT;

CREATE ROLE IF NOT EXISTS SEMESTEROS_BACKEND;

GRANT USAGE ON DATABASE SEMESTEROS TO ROLE SEMESTEROS_BACKEND;
GRANT USAGE ON SCHEMA SEMESTEROS.APP TO ROLE SEMESTEROS_BACKEND;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE SEMESTEROS_BACKEND;

-- An internal stage requires READ before WRITE can be granted.
GRANT READ ON STAGE SEMESTEROS.APP.SYLLABI TO ROLE SEMESTEROS_BACKEND;
GRANT WRITE ON STAGE SEMESTEROS.APP.SYLLABI TO ROLE SEMESTEROS_BACKEND;

GRANT SELECT, INSERT, UPDATE ON TABLE SEMESTEROS.APP.SYLLABUS_UPLOADS TO ROLE SEMESTEROS_BACKEND;

GRANT ROLE SEMESTEROS_BACKEND TO USER SEMESTEROS_API;

SHOW GRANTS TO ROLE SEMESTEROS_BACKEND;
SHOW GRANTS TO USER SEMESTEROS_API;
